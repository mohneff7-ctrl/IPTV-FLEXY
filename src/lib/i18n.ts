export type I18nKey = keyof typeof dict;

export function translate(lang: 'ar' | 'en', key: I18nKey, vars?: Record<string, string | number>): string {
  let s: string = dict[key]?.[lang === 'ar' ? 0 : 1] ?? key;
  if (vars) Object.entries(vars).forEach(([k, v]) => (s = s.replace(`{${k}}`, String(v))));
  return s;
}

export function useT() {
  const lang = useSettings((s) => s.lang);
  return (key: I18nKey, vars?: Record<string, string | number>) => translate(lang, key, vars);
}

